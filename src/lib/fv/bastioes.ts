export const BASTIOES_DB: Bastiao[] = rawBastiões.split('\n')
  .filter(line => line.trim().length > 0)
  .map(line => {
    const cols = line.split('\t');
    const idNum = cols[0] ? cols[0].trim() : '';
    const titulo = cols[1] ? cols[1].trim() : '';
    const ano = cols[2] ? cols[2].trim() : '';
    
    // Ignora linhas incompletas ou que não tenham ID válido
    if (!idNum || !titulo || isNaN(parseInt(idNum, 10))) return null;

    return {
      numero: idNum,
      titulo: titulo,
      ano: ano,
      nomeCompleto: `Bastião ${idNum} (${ano}) - ${titulo}`,
      link: gerarLinkDoKoha(ano)
    };
  })
  .filter((b): b is Bastiao => !!b); // Limpa os nulls
